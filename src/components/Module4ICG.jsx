import React, { useMemo, useState } from 'react';
import { generateBackpatching, translateSwitchCase, parseSwitchCases } from '../engine/icgEngine';
import { Tabs, Listing, Stat } from './ui';
import { LabSource } from './lab/LabSource';
import { QuadTable, TripleTable } from './studio/PhaseViews';
import { irLines } from './studio/irPresentation';
import { Code, GitBranch, Layers } from 'lucide-react';

const BOOL_PRESETS = ['a < b || c < d && e < f', 'x > 0 && (y < 10 || z == 0)', '!(p == q) || r >= s', 'true && m != n'];

export function Module4ICG() {
  const [tab, setTab] = useState('tac');
  return (
    <div className="module-wrapper">
      <Tabs
        label="Intermediate code views"
        active={tab}
        onChange={setTab}
        tabs={[
          { id: 'tac', label: 'TAC, quadruples & triples', icon: Code },
          { id: 'backpatch', label: 'Backpatching', icon: GitBranch },
          { id: 'switch', label: 'Switch translation', icon: Layers },
        ]}
      />
      {tab === 'tac' && <TacPanel />}
      {tab === 'backpatch' && <BackpatchPanel />}
      {tab === 'switch' && <SwitchPanel />}
    </div>
  );
}

function TacPanel() {
  return (
    <LabSource initialId="arithmetic">
      {(result) => {
        const ir = result.phases.ir.output;
        return (
          <div className="grid-2col">
            <div className="panel-card">
              <h3 className="panel-title">Three-address code</h3>
              <p className="explain">Generated by the Studio&apos;s IR generator from the type-checked AST. Every instruction has at most one operator.</p>
              <Listing lines={irLines(ir.instructions)} ariaLabel="Three-address code" />
              <h3 className="panel-title mt-16">Quadruples (op, arg1, arg2, result)</h3>
              <QuadTable quads={ir.quadruples} />
            </div>
            <div className="panel-card">
              <h3 className="panel-title">Triples (op, arg1, arg2)</h3>
              <p className="explain">
                A triple has no result field: later instructions refer to its value by position <code>(i)</code>. Labels disappear, so jump
                targets become triple numbers – which is why reordering triples is hard.
              </p>
              <TripleTable triples={ir.triples} />
              <h3 className="panel-title mt-16">Indirect triples</h3>
              <p className="explain">
                A separate statement list points into the triple table. An optimiser can reorder the statement list without renumbering the
                triples themselves.
              </p>
              <div className="table-wrapper">
                <table className="table-compact">
                  <thead>
                    <tr>
                      <th>Statement</th>
                      <th>Triple</th>
                      <th>Operation</th>
                    </tr>
                  </thead>
                  <tbody>
                    {ir.indirectTriples.statements.map((s) => {
                      const t = ir.triples[s.pointsTo];
                      return (
                        <tr key={s.position}>
                          <td>{s.position}</td>
                          <td>({s.pointsTo})</td>
                          <td className="mono small">
                            {t.op} {t.arg1} {t.arg2}
                          </td>
                        </tr>
                      );
                    })}
                  </tbody>
                </table>
              </div>
            </div>
          </div>
        );
      }}
    </LabSource>
  );
}

function BackpatchPanel() {
  const [expr, setExpr] = useState(BOOL_PRESETS[0]);
  const { result, error } = useMemo(() => {
    try {
      return { result: generateBackpatching(expr), error: '' };
    } catch (e) {
      return { result: null, error: e.message };
    }
  }, [expr]);

  return (
    <>
      <div className="input-card">
        <div className="field-group">
          <label htmlFor="bp-expr">Boolean expression (&amp;&amp; || ! or and/or/not, comparisons, true/false)</label>
          <input id="bp-expr" type="text" value={expr} onChange={(e) => setExpr(e.target.value)} />
        </div>
        <div className="preset-buttons mt-8">
          {BOOL_PRESETS.map((p) => (
            <button key={p} className="btn-secondary" onClick={() => setExpr(p)}>
              {p}
            </button>
          ))}
        </div>
        {error && <div className="error-banner">{error}</div>}
      </div>
      {result && (
        <div className="grid-2col">
          <div className="panel-card">
            <h3 className="panel-title">Quadruples after the expression&apos;s backpatching</h3>
            <p className="explain">
              Code is emitted in one pass with jump targets left blank (<code>_</code>). When a marker <code>M</code> later learns the address
              of the next instruction, <code>backpatch(list, M.instr)</code> fills the targets on that list. Jumps still on{' '}
              <strong>B.truelist</strong> / <strong>B.falselist</strong> are filled by the enclosing statement (if, while…).
            </p>
            <div className="stat-row">
              <Stat label="B.truelist" value={`{${result.truelist.join(', ')}}`} />
              <Stat label="B.falselist" value={`{${result.falselist.join(', ')}}`} />
              <Stat label="next instr" value={result.nextQuad} />
            </div>
            <div className="table-wrapper">
              <table className="table-compact">
                <thead>
                  <tr>
                    <th>Quad</th>
                    <th>As emitted</th>
                    <th>After backpatching</th>
                    <th>Open list</th>
                  </tr>
                </thead>
                <tbody>
                  {result.backpatchedCode.map((q, i) => (
                    <tr key={q.quad}>
                      <td>{q.quad}</td>
                      <td>
                        <code className="text-muted">{result.originalCode[i].instruction}</code>
                      </td>
                      <td>
                        <code className={q.instruction.endsWith('_') ? '' : 'text-success'}>{q.instruction}</code>
                      </td>
                      <td>{q.truelist ? 'truelist' : q.falselist ? 'falselist' : '—'}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>
          <div className="panel-card">
            <h3 className="panel-title">Semantic actions in execution order</h3>
            <div className="step-logs" style={{ maxHeight: 420 }}>
              {result.stepLogs.map((l, i) => (
                <div key={i} className="step-log-item">
                  {i + 1}. {l}
                </div>
              ))}
            </div>
          </div>
        </div>
      )}
    </>
  );
}

function SwitchPanel() {
  const [subject, setSubject] = useState('grade');
  const [casesText, setCasesText] = useState('1: points = 10\n2: points = 7\n3: points = 4\ndefault: points = 0');
  const { result, error } = useMemo(() => {
    try {
      const { cases, defaultAction } = parseSwitchCases(casesText);
      return { result: translateSwitchCase(subject, cases, defaultAction), error: '' };
    } catch (e) {
      return { result: null, error: e.message };
    }
  }, [subject, casesText]);
  return (
    <div className="grid-2col">
      <div className="panel-card">
        <div className="field-group mb-12">
          <label htmlFor="sw-subject">switch ( expression )</label>
          <input id="sw-subject" type="text" value={subject} onChange={(e) => setSubject(e.target.value)} />
        </div>
        <div className="field-group">
          <label htmlFor="sw-cases">Cases – one per line: value: statement, and optionally default: statement</label>
          <textarea id="sw-cases" rows={6} value={casesText} onChange={(e) => setCasesText(e.target.value)} />
        </div>
        {error && <div className="error-banner">{error}</div>}
        <p className="explain mt-12">
          The Dragon Book layout puts the case bodies first and all tests at the end, so the tests can be emitted after every case value is
          known (or replaced by a jump table). Without a default, an unmatched value leaves the switch.
        </p>
      </div>
      <div className="panel-card">
        <h3 className="panel-title">Three-address code</h3>
        {result && <Listing lines={result.tac.map((t) => ({ text: t, kind: t.endsWith(':') ? 'label' : undefined }))} ariaLabel="Switch translation" />}
        <p className="small muted mt-8">MiniC itself has no switch statement; this translation is a stand-alone demonstration.</p>
      </div>
    </div>
  );
}
